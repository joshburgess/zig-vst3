const lv2 = @import("zig-vst3-plugin-core").lv2;
const ui = lv2.ui;

export fn zig_lv2_layout_value(index: u32) usize {
    return switch (index) {
        0 => @sizeOf(lv2.Feature),
        1 => @alignOf(lv2.Feature),
        2 => @offsetOf(lv2.Feature, "URI"),
        3 => @offsetOf(lv2.Feature, "data"),
        4 => @sizeOf(lv2.Descriptor),
        5 => @alignOf(lv2.Descriptor),
        6 => @offsetOf(lv2.Descriptor, "URI"),
        7 => @offsetOf(lv2.Descriptor, "instantiate"),
        8 => @offsetOf(lv2.Descriptor, "connect_port"),
        9 => @offsetOf(lv2.Descriptor, "activate"),
        10 => @offsetOf(lv2.Descriptor, "run"),
        11 => @offsetOf(lv2.Descriptor, "deactivate"),
        12 => @offsetOf(lv2.Descriptor, "cleanup"),
        13 => @offsetOf(lv2.Descriptor, "extension_data"),
        14 => @sizeOf(lv2.UridMap),
        15 => @alignOf(lv2.UridMap),
        16 => @offsetOf(lv2.UridMap, "handle"),
        17 => @offsetOf(lv2.UridMap, "map"),
        18 => @sizeOf(lv2.StateInterface),
        19 => @alignOf(lv2.StateInterface),
        20 => @offsetOf(lv2.StateInterface, "save"),
        21 => @offsetOf(lv2.StateInterface, "restore"),
        22 => @sizeOf(lv2.StateStatus),
        23 => @intFromEnum(lv2.StateStatus.no_space),
        24 => lv2.state_is_pod | lv2.state_is_portable,
        25 => @sizeOf(lv2.Atom),
        26 => @alignOf(lv2.Atom),
        27 => @sizeOf(lv2.AtomEvent),
        28 => @alignOf(lv2.AtomEvent),
        29 => @offsetOf(lv2.AtomEvent, "time"),
        30 => @offsetOf(lv2.AtomEvent, "body"),
        31 => @sizeOf(lv2.AtomSequenceBody),
        32 => @sizeOf(lv2.AtomSequence),
        33 => @offsetOf(lv2.AtomSequence, "atom"),
        34 => @offsetOf(lv2.AtomSequence, "body"),
        35 => @sizeOf(lv2.AtomObjectBody),
        36 => @sizeOf(lv2.AtomObject),
        37 => @offsetOf(lv2.AtomObject, "body"),
        38 => @sizeOf(lv2.AtomPropertyBody),
        39 => @offsetOf(lv2.AtomPropertyBody, "value"),
        40 => @sizeOf(lv2.AtomFloat),
        41 => @offsetOf(lv2.AtomFloat, "body"),
        42 => @sizeOf(lv2.AtomDouble),
        43 => @alignOf(lv2.AtomDouble),
        44 => @offsetOf(lv2.AtomDouble, "body"),
        45 => @sizeOf(lv2.AtomInt),
        46 => @sizeOf(lv2.AtomLong),
        47 => @alignOf(lv2.AtomLong),
        48 => @offsetOf(lv2.AtomLong, "body"),
        49 => @sizeOf(lv2.OptionsContext),
        50 => @intFromEnum(lv2.OptionsContext.port),
        51 => @sizeOf(lv2.OptionsOption),
        52 => @alignOf(lv2.OptionsOption),
        53 => @offsetOf(lv2.OptionsOption, "context"),
        54 => @offsetOf(lv2.OptionsOption, "subject"),
        55 => @offsetOf(lv2.OptionsOption, "key"),
        56 => @offsetOf(lv2.OptionsOption, "size"),
        57 => @offsetOf(lv2.OptionsOption, "type"),
        58 => @offsetOf(lv2.OptionsOption, "value"),
        59 => @sizeOf(lv2.OptionsStatus),
        60 => @sizeOf(lv2.OptionsInterface),
        61 => @alignOf(lv2.OptionsInterface),
        62 => @offsetOf(lv2.OptionsInterface, "get"),
        63 => @offsetOf(lv2.OptionsInterface, "set"),
        64 => lv2.options_status_unknown |
            lv2.options_status_bad_subject |
            lv2.options_status_bad_key |
            lv2.options_status_bad_value,
        65 => @sizeOf(lv2.WorkerStatus),
        66 => @intFromEnum(lv2.WorkerStatus.no_space),
        67 => @sizeOf(lv2.WorkerSchedule),
        68 => @alignOf(lv2.WorkerSchedule),
        69 => @offsetOf(lv2.WorkerSchedule, "handle"),
        70 => @offsetOf(lv2.WorkerSchedule, "schedule_work"),
        71 => @sizeOf(lv2.WorkerInterface),
        72 => @alignOf(lv2.WorkerInterface),
        73 => @offsetOf(lv2.WorkerInterface, "work"),
        74 => @offsetOf(lv2.WorkerInterface, "work_response"),
        75 => @offsetOf(lv2.WorkerInterface, "end_run"),
        76 => @sizeOf(ui.Feature),
        77 => @alignOf(ui.Feature),
        78 => @sizeOf(ui.Descriptor),
        79 => @alignOf(ui.Descriptor),
        80 => @offsetOf(ui.Descriptor, "URI"),
        81 => @offsetOf(ui.Descriptor, "instantiate"),
        82 => @offsetOf(ui.Descriptor, "cleanup"),
        83 => @offsetOf(ui.Descriptor, "port_event"),
        84 => @offsetOf(ui.Descriptor, "extension_data"),
        85 => @sizeOf(ui.IdleInterface),
        86 => @alignOf(ui.IdleInterface),
        87 => @offsetOf(ui.IdleInterface, "idle"),
        88 => @sizeOf(ui.Resize),
        89 => @alignOf(ui.Resize),
        90 => @offsetOf(ui.Resize, "handle"),
        91 => @offsetOf(ui.Resize, "ui_resize"),
        92 => @sizeOf(ui.ResizeInterface),
        93 => @alignOf(ui.ResizeInterface),
        94 => @offsetOf(ui.ResizeInterface, "ui_resize"),
        95 => @sizeOf(ui.ShowInterface),
        96 => @alignOf(ui.ShowInterface),
        97 => @offsetOf(ui.ShowInterface, "show"),
        98 => @offsetOf(ui.ShowInterface, "hide"),
        99 => @sizeOf(ui.Touch),
        100 => @alignOf(ui.Touch),
        101 => @offsetOf(ui.Touch, "handle"),
        102 => @offsetOf(ui.Touch, "touch"),
        103 => @sizeOf(lv2.ProgramDescriptor),
        104 => @alignOf(lv2.ProgramDescriptor),
        105 => @offsetOf(lv2.ProgramDescriptor, "bank"),
        106 => @offsetOf(lv2.ProgramDescriptor, "program"),
        107 => @offsetOf(lv2.ProgramDescriptor, "name"),
        108 => @sizeOf(lv2.ProgramsInterface),
        109 => @alignOf(lv2.ProgramsInterface),
        110 => @offsetOf(lv2.ProgramsInterface, "get_program"),
        111 => @offsetOf(lv2.ProgramsInterface, "select_program"),
        112 => @sizeOf(ui.ProgramsUiInterface),
        113 => @alignOf(ui.ProgramsUiInterface),
        114 => @offsetOf(ui.ProgramsUiInterface, "select_program"),
        115 => @sizeOf(lv2.StateMapPath),
        116 => @alignOf(lv2.StateMapPath),
        117 => @offsetOf(lv2.StateMapPath, "handle"),
        118 => @offsetOf(lv2.StateMapPath, "abstract_path"),
        119 => @offsetOf(lv2.StateMapPath, "absolute_path"),
        120 => @sizeOf(lv2.StateMakePath),
        121 => @alignOf(lv2.StateMakePath),
        122 => @offsetOf(lv2.StateMakePath, "handle"),
        123 => @offsetOf(lv2.StateMakePath, "path"),
        124 => @sizeOf(lv2.StateFreePath),
        125 => @alignOf(lv2.StateFreePath),
        126 => @offsetOf(lv2.StateFreePath, "handle"),
        127 => @offsetOf(lv2.StateFreePath, "free_path"),
        128 => @sizeOf(lv2.AtomBool),
        129 => @alignOf(lv2.AtomBool),
        130 => @offsetOf(lv2.AtomBool, "body"),
        131 => @sizeOf(lv2.AtomUrid),
        132 => @alignOf(lv2.AtomUrid),
        133 => @offsetOf(lv2.AtomUrid, "body"),
        else => std.math.maxInt(usize),
    };
}

const std = @import("std");
