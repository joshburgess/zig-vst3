// ISO/IEC 11172-3:1993, Annex B, Table 3-B.7. Entries retain the
// standard's x-major, y-minor cell order, codeword length, and unsigned bits.

pub const Entry = struct {
    length: u5,
    bits: u19,
};

pub const Table = struct {
    side: u5,
    linbits: u4,
    entries: []const Entry,
};

pub fn get(index: u5) !Table {
    return switch (index) {
        0 => makeTable(1, 0, &table0_entries),
        1 => makeTable(2, 0, &table1_entries),
        2 => makeTable(3, 0, &table2_entries),
        3 => makeTable(3, 0, &table3_entries),
        5 => makeTable(4, 0, &table5_entries),
        6 => makeTable(4, 0, &table6_entries),
        7 => makeTable(6, 0, &table7_entries),
        8 => makeTable(6, 0, &table8_entries),
        9 => makeTable(6, 0, &table9_entries),
        10 => makeTable(8, 0, &table10_entries),
        11 => makeTable(8, 0, &table11_entries),
        12 => makeTable(8, 0, &table12_entries),
        13 => makeTable(16, 0, &table13_entries),
        15 => makeTable(16, 0, &table15_entries),
        16 => makeTable(16, 1, &table16_entries),
        17 => makeTable(16, 2, &table16_entries),
        18 => makeTable(16, 3, &table16_entries),
        19 => makeTable(16, 4, &table16_entries),
        20 => makeTable(16, 6, &table16_entries),
        21 => makeTable(16, 8, &table16_entries),
        22 => makeTable(16, 10, &table16_entries),
        23 => makeTable(16, 13, &table16_entries),
        24 => makeTable(16, 4, &table24_entries),
        25 => makeTable(16, 5, &table24_entries),
        26 => makeTable(16, 6, &table24_entries),
        27 => makeTable(16, 7, &table24_entries),
        28 => makeTable(16, 8, &table24_entries),
        29 => makeTable(16, 9, &table24_entries),
        30 => makeTable(16, 11, &table24_entries),
        31 => makeTable(16, 13, &table24_entries),
        4, 14 => error.InvalidMp3HuffmanTable,
    };
}

fn makeTable(
    side: u5,
    linbits: u4,
    entries: []const Entry,
) Table {
    return .{
        .side = side,
        .linbits = linbits,
        .entries = entries,
    };
}

